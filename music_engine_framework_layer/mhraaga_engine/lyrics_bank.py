TAGS = {"hindi": ("Mukhda", "Antara"), "marathi": ("Mukhda", "Antara"), "english": ("Chorus", "Verse")}


def make_lyrics(language: str, theme: str = "", rng: random.Random | None = None) -> tuple[str, str]:
    rng = rng or random.Random()
    language = language if language in BANK else "hindi"
    theme = theme if theme in THEMES else rng.choice(THEMES)
    t = BANK[language][theme]
    m1, a1 = rng.choice(t["m"]), rng.choice(t["a"])
    m, a = TAGS.get(language, ("Mukhda", "Antara"))
    return f"[{m}]\n{m1}\n[{a}]\n{a1}", theme
